// Goose compiler - the extern symbol names a native part's table carries:
// what the files a package holds name as C symbols (read by the lexer
// alone, since these are files the program never parses), and the
// goose_symbols.c those names go into. Kept apart from native.h so a test
// of the table's hardening compiles without the build machinery around it.
#pragma once

#include "lexer.h"

namespace goose {

// The C symbols a file's extern fns name: `extern fn f(...) = "sym"` (or the
// deprecated `extern "sym" fn f`) gives sym, `extern fn f` or `extern fn
// ns::f` gives the leaf name (section 7.10). Read by the lexer alone, since this is
// asked of files the program never parsed. The libraries the file's extern
// blocks name go into `libs`, where it is given.
inline void ExternNamesIn(const string &path, const string &text, set<string> &names,
                          set<string> *libs = nullptr) {
    Lexer lex(path, text.c_str());
    while (lex.tok != T_EOF) {
        if (lex.tok != T_EXTERN) {
            lex.Next();
            continue;
        }
        lex.Next();
        string cname;
        if (lex.tok == T_STRLIT) {
            cname = lex.sval;
            lex.Next();
        }
        // An extern block's functions come from its shared library (section 7.10),
        // not from the native part: skipped through its `}`.
        if (lex.tok == T_LCURLY) {
            if (libs && !cname.empty()) libs->insert(cname);
            auto depth = 0;
            do {
                if (lex.tok == T_LCURLY) depth++;
                else if (lex.tok == T_RCURLY) depth--;
                lex.Next();
            } while (depth > 0 && lex.tok != T_EOF);
            continue;
        }
        if (lex.tok != T_FN) continue;
        lex.Next();
        if (lex.tok == T_IDENT) {
            string leaf(lex.attr);
            lex.Next();
            if (lex.tok == T_COLONCOLON) {
                lex.Next();
                if (lex.tok == T_IDENT) leaf = string(lex.attr);
            }
            // Past the signature to its `;`: an `=` outside the parameters'
            // parentheses (where defaults have theirs) is the symbol's.
            auto parens = 0;
            while (lex.tok != T_SEMI && lex.tok != T_EOF && lex.tok != T_EXTERN) {
                if (lex.tok == T_LPAREN) parens++;
                else if (lex.tok == T_RPAREN) parens--;
                else if (lex.tok == T_ASSIGN && parens == 0) {
                    lex.Next();
                    if (lex.tok == T_STRLIT) cname = lex.sval;
                    continue;
                }
                lex.Next();
            }
            if (cname.empty()) cname = leaf;
        }
        if (!cname.empty()) names.insert(cname);
    }
}

// Whether n is a C identifier, the rule CheckExternSpec (typecheck_calls.h)
// enforces on the names typecheck saw: a leading underscore allowed, digits
// not first, and only ASCII letters, digits and underscores.
inline bool CIdentifier(string_view n) {
    if (n.empty() || isdigit((unsigned char)n[0])) return false;
    for (auto c : n)
        if (!(isalnum((unsigned char)c) || c == '_')) return false;
    return true;
}

// n as a C string literal, CodeGen::CStr's escaping for one that is short
// enough to never need its splitting: a quote or backslash escaped, any
// other byte outside the printable ASCII an octal escape. A name the
// typecheck never saw reaches the generated C through this, so what its
// text carries stays inside the literal.
inline string CSymLiteral(string_view n) {
    string s = "\"";
    for (auto c : n) {
        auto u = (uint8_t)c;
        if (c == '"' || c == '\\') { s += '\\'; s += c; }
        else if (u >= 32 && u < 127) s += c;
        else {
            char buf[8];
            snprintf(buf, sizeof(buf), "\\%03o", u);
            s += buf;
        }
    }
    s += '"';
    return s;
}

// goose_symbols.c: the one exported function of a package's JIT library,
// handing out the table of its functions by name. Taking a function's
// address needs no signature, so each is declared `void f(void)`. A name
// the typecheck never saw (ExternNamesIn asks files the program does not
// parse) is only written when it is a C identifier, the same rule
// CheckExternSpec enforces; the literal keeps C's escaping, so a name
// from a hostile source cannot end the string or add a line here.
inline string SymbolTableSource(const string &pkgname, const vector<string> &names) {
    string s = cat("/* Generated by the Goose compiler for the package ", pkgname,
                   ": the C functions its\n   extern fns name, which a JIT run looks up through "
                   "goose_symbols. Do not edit. */\n\n"
                   "typedef struct { const char *name; const void *addr; } goose_symbol;\n\n");
    for (auto &n : names)
        if (CIdentifier(n)) Append(s, "void ", n, "(void);\n");
    Append(s, "\n#ifdef _WIN32\n__declspec(dllexport)\n#endif\n"
              "const goose_symbol *goose_symbols(void) {\n"
              "    static const goose_symbol table[] = {\n");
    for (auto &n : names)
        if (CIdentifier(n))
            Append(s, "        { ", CSymLiteral(n), ", (const void *)&", n, " },\n");
    s += "        { 0, 0 }\n    };\n    return table;\n}\n";
    return s;
}

}  // namespace goose
