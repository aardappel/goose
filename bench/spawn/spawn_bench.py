BATCH_RE = re.compile(r"^batch (.*)$")


def parse_batches(out):
    rows = []
    for line in out.splitlines():
        m = BATCH_RE.match(line.strip())
        if not m:
            continue
        kv = dict(f.split("=", 1) for f in m.group(1).split())
        rows.append({k: int(v) for k, v in kv.items()})
    return rows


def quantile(xs, q):
    xs = sorted(xs)
    if not xs:
        return float("nan")
    k = (len(xs) - 1) * q
    lo, hi = math.floor(k), math.ceil(k)
    return xs[lo] + (xs[hi] - xs[lo]) * (k - lo)


def summarize(rows):
    per = [r["ns"] / r["units"] for r in rows if r.get("units")]
    s = {"median": statistics.median(per), "p10": quantile(per, 0.1),
         "p90": quantile(per, 0.9), "min": min(per), "batches": len(per),
         "units": rows[0]["units"]}
    for k in ("x0", "x1", "x2", "x3"):
        if any(r.get(k) for r in rows):
            s[k] = statistics.median(r[k] / r["units"] for r in rows)
    return s


def run_point(exe, args, label, reps_noisy=1):
    """Runs one timed program, re-running once if its spread is wide."""
    for attempt in range(1 + reps_noisy):
        r = tc.run_measured(exe, args)
        if r.code != 0:
            return {"error": f"exit {r.code}: {(r.err or r.out)[-300:]}"}
        rows = parse_batches(r.out)
        if not rows:
            return {"error": f"no batch lines: {r.out[-300:]}"}
        s = summarize(rows)
        s["peak"] = r.peak
        if s["p90"] <= 1.5 * s["p10"] or attempt == reps_noisy:
            if s["p90"] > 1.5 * s["p10"]:
                s["noisy"] = True
            return s
        print(f"    {label}: spread {s['p90'] / s['p10']:.2f}x, re-measuring", flush=True)


def fit_line(xs, ys):
    n = len(xs)
    if n < 2:
        return None
    mx, my = sum(xs) / n, sum(ys) / n
    sxx = sum((x - mx) ** 2 for x in xs)
    if sxx == 0:
        return None
    b = sum((x - mx) * (y - my) for x, y in zip(xs, ys)) / sxx
    a = my - b * mx
    ss_tot = sum((y - my) ** 2 for y in ys)
    ss_res = sum((y - (a + b * x)) ** 2 for x, y in zip(xs, ys))
    r2 = 1 - ss_res / ss_tot if ss_tot else 1.0
    return {"a": a, "b": b, "r2": r2}


