# --- Goose program text ---------------------------------------------------------
#
# Every program has the same skeleton: `run(reps, sources...)` does the timed
# work and says how many units (spawns, tasks, round trips) that was;
# `check(sources...)` verifies what workers receive; main calibrates, warms up
# and prints one line per batch. Source data for arguments is built by main as
# locals and handed to run by reference: as globals they would grow
# gs_globals_t, which every worker callocs, and that is a cost of its own (B8).

SKELETON = """\
// Generated by bench/spawn/spawn_bench.py; do not edit.
// @ID@: @TITLE@ (@PARAM@ = @VALUE@)
import os;

let CHECK = @CHECK@;
let TARGET_NS = @TARGET@;
let BATCHES = @BATCHES@;
// No worker's checksum is this; comparing against it keeps what a worker
// reads observable without ever taking the branch.
let SENTINEL = -987654321;

struct Sum { v: i64 }
struct Out { units: i64, x: i64[4] }

fn bytes_of_len(n: i64) -> u8[>..] {
    var b: u8[>..] = [];
    for i in n { b.push((i % 251 + 1) as u8); }
    return b;
}

@DECLS@

fn run(reps: i64@SRCPARAMS_TAIL@) -> Out {
@RUN@
}

fn check(@SRCPARAMS@) {
@CHECKBODY@
}

fn teardown(@SRCPARAMS@) {
@TEARDOWN@
}

fn main() {
@SETUP@
    if CHECK {
        check(@SRCARGS@);
        teardown(@SRCARGS@);
        return;
    }
    // Every run's result reaches the output: a run with no side effects
    // (E6i) would otherwise be deleted from the calibration loop, which
    // would then double reps until it overflowed.
    var sink = 0;
    let w0 = clock_ns();
    var warm = 0;
    while warm < 50 && clock_ns() - w0 < TARGET_NS / 4 {
        sink += run(1@SRCARGS_TAIL@).x[0];
        warm++;
    }
    var reps = 1;
    loop {
        let t = clock_ns();
        sink += run(reps@SRCARGS_TAIL@).x[0];
        if clock_ns() - t >= TARGET_NS { break; }
        if reps >= 1099511627776 { abort("calibration never reached TARGET_NS"); }
        reps *= 2;
    }
    for b in BATCHES {
        let t = clock_ns();
        let o = run(reps@SRCARGS_TAIL@);
        let ns = clock_ns() - t;
        print("batch units=", o.units, " ns=", ns, " x0=", o.x[0], " x1=", o.x[1],
              " x2=", o.x[2], " x3=", o.x[3]);
    }
    print("sink ", sink);
    teardown(@SRCARGS@);
}
"""


def indent(text, n=4):
    pad = " " * n
    return "\n".join(pad + l if l.strip() else l for l in text.strip("\n").split("\n"))


@dataclass
class Prog:
    """The parts of one generated program that differ between benchmarks."""
    decls: str = ""
    run: str = ""
    check: str = '    print("check ok");'
    teardown: str = ""
    setup: str = ""
    # (name, type) of each main local handed to run/check/teardown by reference.
    sources: list = field(default_factory=list)
    defines: list = field(default_factory=list)

    def render(self, meta, check, target, batches):
        params = ", ".join(f"{n}: const {t}&" for n, t in self.sources)
        args = ", ".join(n for n, _ in self.sources)
        tail = lambda s: (", " + s) if s else ""
        subs = {
            "@ID@": meta["id"], "@TITLE@": meta["title"], "@PARAM@": meta["param"],
            "@VALUE@": str(meta["value"]),
            "@CHECK@": "true" if check else "false", "@TARGET@": str(target),
            "@BATCHES@": str(batches), "@DECLS@": self.decls.strip("\n"),
            "@SRCPARAMS_TAIL@": tail(params), "@SRCPARAMS@": params,
            "@SRCARGS_TAIL@": tail(args), "@SRCARGS@": args,
            "@RUN@": indent(self.run), "@CHECKBODY@": indent(self.check),
            "@TEARDOWN@": indent(self.teardown), "@SETUP@": indent(self.setup),
        }
        text = SKELETON
        for k, v in subs.items():
            text = text.replace(k, v)
        return text


# --- the serial spawn shape: one worker, its arguments and globals --------------
#
# An argument or a global is a kind plus a size. Each kind knows its parameter
# type, how main builds the source value, the expression that passes it, and
# the statements that fold it into the worker's checksum. The same statements
# run in `expect`, a plain function with the worker's parameters, so the
# CHECK build compares the worker's view against main's.

def arg_parts(i, kind, n=0, m=0):
    """(param type, setup, source (name, type) or None, spawn expr, fold)."""
    a, s = f"a{i}", f"src{i}"
    if kind == "i64":
        return "i64", "", None, f"i + {i + 1}", f"s += {a};"
    if kind == "fixed":
        t = f"i64[{n}]"
        setup = f"var {s}: {t} = [0; {n}];\n{s}[0] = {i + 3};\n{s}[{n - 1}] = {i + 5};"
        return t, setup, (s, t), s, f"s += {a}[0] + {a}[{n - 1}];"
    if kind == "resz":
        t = "i64[>..]"
        setup = f"var {s}: {t} = [];\nfor j in {n} {{ {s}.push(j + {i}); }}"
        return t, setup, (s, t), f"copy({s})", \
            f"s += {a}.len;\nif {a}.len > 0 {{ s += {a}[{a}.len - 1]; }}"
    if kind == "var":
        t = "u8[]"
        setup = f"let {s}: {t} = bytes_of_len({n});"
        return t, setup, (s, t), f"copy({s})", \
            f"s += {a}.len;\nif {a}.len > 0 {{ s += {a}[{a}.len - 1]; }}"
    if kind == "strings":
        # n strings of m bytes each.
        t = "u8[][>..]"
        setup = f"var {s}: {t} = [];\nfor j in {n} {{ {s}.push(bytes_of_len({m})); }}"
        return t, setup, (s, t), f"copy({s})", f"s += {a}.len;"
    if kind == "frame":
        t = "Bag"
        setup = (f"var {s} = Bag {{ id: {i + 7}, data: [] }};\n"
                 f"for j in {n} {{ {s}.data.push(j); }}")
        return t, setup, (s, t), f"copy({s})", f"s += {a}.id + {a}.data.len;"
    raise ValueError(kind)


def global_parts(i, kind, n=0, prefix="g"):
    """(declaration, setup, fold)."""
    g = f"{prefix}{i}"
    if kind == "i64":
        return f"var {g}: i64 = {i + 1};", "", f"s += {g};"
    if kind == "fixed":
        return (f"var {g}: i64[{n}] = [0; {n}];", f"{g}[0] = {i + 3};\n{g}[{n - 1}] = {i + 5};",
                f"s += {g}[0] + {g}[{n - 1}];")
    if kind == "resz":
        return (f"var {g}: i64[>..] = [];", f"for j in {n} {{ {g}.push(j + {i}); }}",
                f"s += {g}.len;\nif {g}.len > 0 {{ s += {g}[{g}.len - 1]; }}")
    if kind == "var":
        return (f"var {g}: u8[] = bytes_of_len({n});", "",
                f"s += {g}.len;\nif {g}.len > 0 {{ s += {g}[{g}.len - 1]; }}")
    if kind == "pool":
        # 2n slots, every other one freed: n freelist entries none of which
        # touch, so the freelist holds n spans.
        return (f"reusable var {g}: i64[>..] = [];",
                f"for j in {2 * n + 1} {{ {g}.alloc_index(j); }}\n"
                f"for j in {n} {{ {g}.free(2 * j); }}",
                f"s += {g}.len;")
    if kind == "const":
        return (f"const {g}: i64[4] = [{i}, 1, 2, {i + 3}];", "", f"s += {g}[0] + {g}[3];")
    raise ValueError(kind)


def serial(args=(), used=(), unused=(), cold=(), body="", body_decls=""):
    """A worker given `args`, naming the globals in `used`, the program also
    declaring the never-named `unused` ones and the `cold` ones named only on
    a branch the worker never takes; spawned and waited for one at a time.
    Each of args/used/unused/cold is a list of (kind, n[, m]) tuples."""
    p = Prog()
    params, setup, spawn, fold, decls = [], [], [], [], [body_decls]
    if any(a[0] == "frame" for a in args):
        decls.append("struct Bag { id: i64, data: i64[>..] }")
    for i, a in enumerate(args):
        t, st, src, ex, fo = arg_parts(i, *a)
        params.append(f"a{i}: {t}")
        if st:
            setup.append(st)
        if src:
            p.sources.append(src)
        spawn.append(ex)
        fold.append(fo)
    # Prefixes that no index can turn into a type name (u8, i64...).
    for prefix, group in (("g", used), ("unused", unused), ("cold", cold)):
        for i, g in enumerate(group):
            d, st, fo = global_parts(i, *g, prefix=prefix)
            decls.append(d)
            if st:
                setup.append(st)
            if prefix == "g":
                fold.append(fo)
            elif prefix == "cold":
                fold.append(f"if s == SENTINEL {{\n{indent(fo)}\n}}")
    if body:
        fold.append(body)
    fold_text = "var s = 0;\n" + "\n".join(fold)
    plist = ", ".join(params)
    decls.append(f"thread_fn w({plist}) {{\n{indent(fold_text)}\n"
                 f"    if CHECK || s == SENTINEL {{ qput(Sum {{ v: s }}); }}\n}}")
    decls.append(f"fn expect({plist}) -> i64 {{\n{indent(fold_text)}\n    return s;\n}}")
    p.decls = "\n\n".join(d for d in decls if d)
    sargs = ", ".join(["w"] + spawn)
    eargs = ", ".join(spawn)
    p.setup = "\n".join(setup)
    p.run = (f"for i in reps {{ thread_wait(thread_spawn({sargs})); }}\n"
             "return Out { units: reps, x: [0; 4] };")
    p.check = f"""\
for i in 3 {{
    thread_wait(thread_spawn({sargs}));
    let got = qget<Sum>().v;
    let want = expect({eargs});
    if got != want {{
        print("check failed: got ", got, " want ", want);
        exit(1);
    }}
}}
print("check ok");"""
    return p


