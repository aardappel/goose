def stack_chain(k):
    """k nested functions, each holding a resizable local live across the call
    to the next: the worker's call depth reaches k data stacks."""
    fns = ["fn chain0() -> i64 { return 0; }"]
    for j in range(1, k + 1):
        fns.append(f"fn chain{j}() -> i64 {{\n    var a: i64[>..] = [];\n    a.push({j});\n"
                   f"    let r = chain{j - 1}();\n    return a.len + a[0] + r;\n}}")
    return "\n\n".join(fns), f"s += chain{k}();"


def native_recursion(nbytes):
    """Recursion touching about nbytes of native stack (a 480-byte local array
    per frame, below the 4096-byte line past which locals go to data stacks)."""
    depth = max(0, nbytes // 512)
    decl = """\
recursive fn deep(d: i64) -> i64 {
    var a: i64[60] = [0; 60];
    a[d % 60] = d;
    if d == 0 { return a[0]; }
    return deep(d - 1) + a[(d * 7) % 60];
}"""
    return decl, f"s += deep({depth});"


# --- custom shapes -------------------------------------------------------------------

def prog_phases():
    p = Prog()
    p.decls = """\
struct Stamp { a: i64, b: i64 }
thread_fn w() {
    let a = clock_ns();
    qput(Stamp { a: a, b: clock_ns() });
}"""
    # x0: thread_spawn returns; x1: spawn call to the worker's first
    # instruction; x2: worker's last instruction (its qput) to thread_wait
    # returning; x3: the worker body between them.
    p.run = """\
var x: i64[4] = [0; 4];
for i in reps {
    let t0 = clock_ns();
    let id = thread_spawn(w);
    let t1 = clock_ns();
    thread_wait(id);
    let t2 = clock_ns();
    let st = qget<Stamp>();
    x[0] += t1 - t0;
    x[1] += st.a - t0;
    x[2] += t2 - st.b;
    x[3] += st.b - st.a;
}
return Out { units: reps, x: x };"""
    p.check = """\
thread_wait(thread_spawn(w));
let st = qget<Stamp>();
if st.b < st.a { print("check failed: stamps out of order"); exit(1); }
print("check ok");"""
    return p


EMPTY_WORKER = """\
thread_fn w(i: i64) {
    if CHECK { qput(Sum { v: i }); }
}"""


def check_counts(n_expr, sum_expr):
    """Spawns n workers of EMPTY_WORKER's shape and checks every one ran."""
    return f"""\
var total = 0;
for k in {n_expr} {{ total += qget<Sum>().v; }}
if total != {sum_expr} {{ print("check failed: ", total); exit(1); }}
print("check ok");"""


def prog_burst(n, order="fwd"):
    p = Prog()
    p.decls = EMPTY_WORKER
    wait = ("for id in ids { thread_wait(id); }" if order == "fwd" else
            "var k = ids.len - 1;\nwhile k >= 0 { thread_wait(ids[k]); k -= 1; }")
    # x0: time spent in the spawn calls alone.
    p.run = f"""\
var x: i64[4] = [0; 4];
var ids: i64[>..] = [];
for r in reps {{
    ids.clear();
    let t0 = clock_ns();
    for i in {n} {{ ids.push(thread_spawn(w, i)); }}
    x[0] += clock_ns() - t0;
{indent(wait)}
}}
return Out {{ units: reps * {n}, x: x }};"""
    p.check = f"""\
var ids: i64[>..] = [];
for i in {n} {{ ids.push(thread_spawn(w, i)); }}
for id in ids {{ thread_wait(id); }}
""" + check_counts(n, n * (n - 1) // 2)
    return p


def prog_live(n_idle):
    p = Prog()
    p.decls = EMPTY_WORKER + """

struct Quit { v: i64 }
thread_fn idle() {
    let q = qget<Quit>();
}"""
    # The idle population is started before timing, by main, and released at
    # the end; it must not be in run, which the calibration calls repeatedly.
    p.setup = f"var idle_ids: i64[>..] = [];\nfor k in {n_idle} {{ idle_ids.push(thread_spawn(idle)); }}"
    p.sources = [("idle_ids", "i64[>..]")]
    p.run = """\
for i in reps { thread_wait(thread_spawn(w, i)); }
return Out { units: reps, x: [0; 4] };"""
    p.check = """\
for i in 4 { thread_wait(thread_spawn(w, i)); }
""" + check_counts(4, 6)
    p.teardown = """\
for id in idle_ids { qput(Quit { v: 0 }); }
for id in idle_ids { thread_wait(id); }"""
    return p


def prog_parallel(n_spawners):
    p = Prog()
    p.decls = EMPTY_WORKER + """

thread_fn spawner(m: i64) {
    for i in m { thread_wait(thread_spawn(w, 1)); }
}"""
    p.run = f"""\
var ids: i64[>..] = [];
for k in {n_spawners} {{ ids.push(thread_spawn(spawner, reps)); }}
for id in ids {{ thread_wait(id); }}
return Out {{ units: reps * {n_spawners}, x: [0; 4] }};"""
    p.check = f"""\
var ids: i64[>..] = [];
for k in {n_spawners} {{ ids.push(thread_spawn(spawner, 3)); }}
for id in ids {{ thread_wait(id); }}
""" + check_counts(3 * n_spawners, 3 * n_spawners)
    return p


def prog_tree(depth):
    p = Prog()
    p.decls = """\
thread_fn node(d: i64) {
    if CHECK { qput(Sum { v: 1 }); }
    if d > 0 {
        let a = thread_spawn(node, d - 1);
        let b = thread_spawn(node, d - 1);
        thread_wait(a);
        thread_wait(b);
    }
}"""
    nodes = (2 << depth) - 1
    p.run = f"""\
for r in reps {{ thread_wait(thread_spawn(node, {depth})); }}
return Out {{ units: reps * {nodes}, x: [0; 4] }};"""
    p.check = f"thread_wait(thread_spawn(node, {depth}));\n" + check_counts(nodes, nodes)
    return p


def prog_chain(depth):
    p = Prog()
    # Each link copies a 1 KB global from the link that spawned it, which has
    # already changed it: what a worker's worker sees is its parent's.
    p.decls = """\
var g: i64[128] = [0; 128];
thread_fn link(d: i64) {
    g[0] += 1;
    if CHECK { qput(Sum { v: g[0] }); }
    if d > 0 { thread_wait(thread_spawn(link, d - 1)); }
}"""
    p.run = f"""\
for r in reps {{ thread_wait(thread_spawn(link, {depth - 1})); }}
return Out {{ units: reps * {depth}, x: [0; 4] }};"""
    p.check = (f"thread_wait(thread_spawn(link, {depth - 1}));\n"
               + check_counts(depth, depth * (depth + 1) // 2))
    return p


WORK = """\
struct Res { v: i64 }
struct Job { k: i64, seed: i64 }

// k rounds of xorshift: the same task the C, C++ and Rust rows run.
fn work(k: i64, seed: i64) -> i64 {
    var r: u64 = seed as! u64 * 2654435761 + 1;
    for i in k {
        r ^= r << 13;
        r ^= r >> 7;
        r ^= r << 17;
    }
    return (r & 65535) as! i64;
}"""


def prog_task(mode, k):
    p = Prog()
    if mode == "spawn":
        p.decls = WORK + """

thread_fn task(k: i64, seed: i64) { qput(Res { v: work(k, seed) }); }"""
        # Waves of at most 256 live tasks, as the baselines run.
        p.run = f"""\
var ids: i64[>..] = [];
var done = 0;
var acc = 0;
while done < reps {{
    let n = if reps - done < 256 {{ reps - done }} else {{ 256 }};
    ids.clear();
    for j in n {{ ids.push(thread_spawn(task, {k}, done + j)); }}
    for id in ids {{ thread_wait(id); }}
    for j in n {{ acc += qget<Res>().v; }}
    done += n;
}}
return Out {{ units: reps, x: [acc, 0, 0, 0] }};"""
        p.check = f"""\
thread_wait(thread_spawn(task, {k}, 5));
if qget<Res>().v != work({k}, 5) {{ print("check failed"); exit(1); }}
print("check ok");"""
    elif mode == "pool":
        p.decls = WORK + """

thread_fn pooled() {
    loop {
        let j = qget<Job>();
        guard j.k >= 0 else { break; }
        qput(Res { v: work(j.k, j.seed) });
    }
}"""
        p.setup = f"var pool_ids: i64[>..] = [];\nfor k in {HW} {{ pool_ids.push(thread_spawn(pooled)); }}"
        p.sources = [("pool_ids", "i64[>..]")]
        p.run = f"""\
for i in reps {{ qput(Job {{ k: {k}, seed: i }}); }}
var acc = 0;
for i in reps {{ acc += qget<Res>().v; }}
return Out {{ units: reps, x: [acc, 0, 0, 0] }};"""
        p.check = f"""\
qput(Job {{ k: {k}, seed: 5 }});
if qget<Res>().v != work({k}, 5) {{ print("check failed"); exit(1); }}
print("check ok");"""
        p.teardown = """\
for id in pool_ids { qput(Job { k: -1, seed: 0 }); }
for id in pool_ids { thread_wait(id); }"""
    else:
        p.decls = WORK
        p.run = f"""\
var acc = 0;
for i in reps {{ acc += work({k}, i); }}
return Out {{ units: reps, x: [acc, 0, 0, 0] }};"""
    return p


