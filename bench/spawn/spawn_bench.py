#
# A benchmark is a sweep: `points` maps each parameter value to a Prog maker
# and, where one exists, a baseline (mode, a, b). `fit` names the unit of the
# fitted slope, when the sweep is meant to be linear in its parameter; `x`
# gives the fitted quantity for a value when it is not the value itself.

@dataclass
class Bench:
    id: str
    family: str
    title: str
    param: str
    values: list
    make: object                       # value -> Prog, or None for baseline-only
    baseline: object = None            # value -> (mode, a, b) or None
    fit: str = ""                      # unit of the slope, e.g. "ns per global"
    fitx: object = None                # value -> x for the fit
    fmt: object = str                  # value -> table label
    baseline_note: str = ""
    langs: tuple = ("c", "cpp", "rs")


def size_label(n):
    for unit, k in (("GB", GB), ("MB", MB), ("KB", KB)):
        if n >= k and n % k == 0:
            return f"{n // k} {unit}"
    return f"{n} B"


def per_kb(n):
    return n / KB


def nelems(nbytes):
    return max(1, nbytes // 8)


