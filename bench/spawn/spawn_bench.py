def fmt_ns(v):
    if v is None or (isinstance(v, float) and math.isnan(v)):
        return "—"
    if v >= 1e6:
        return f"{v / 1e6:,.2f} ms"
    if v >= 1e4:
        return f"{v / 1e3:,.1f} µs"
    if v >= 1e3:
        return f"{v / 1e3:,.2f} µs"
    return f"{v:,.0f} ns"


def fmt_cell(s):
    if not s:
        return "—"
    if "error" in s:
        return "error"
    cell = fmt_ns(s["median"])
    if s.get("noisy"):
        cell += " ~"
    return cell


