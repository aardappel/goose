def sha(*parts):
    h = hashlib.sha256()
    for p in parts:
        h.update(p if isinstance(p, bytes) else str(p).encode())
        h.update(b"\0")
    return h.hexdigest()[:12]


class Builder:
    def __init__(self, goose, cc, log):
        self.goose = Path(goose)
        st = self.goose.stat()
        self.goose_id = f"{st.st_size}-{st.st_mtime_ns}"
        self.cc = cc
        self.log = log

    def goose_program(self, name, text, defines):
        key = sha(text, self.goose_id, self.cc.name, self.cc.cc, *defines)
        exe = GEN / f"{name}-{key}{tc.EXE_SUFFIX}"
        if exe.exists():
            return exe, None
        src = GEN / f"{name}.goose"
        tc.write_text(src, text)
        cfile = GEN / f"{name}.c"
        code, out, err = tc.run_capture([self.goose, "-O2", "--standalone", "-o", cfile, src])
        tc.write_text(GEN / f"{name}.goose.log", out + err)
        if code != 0:
            return None, f"goose failed, see {name}.goose.log"
        ok, _ = self.cc.compile(cfile, exe, opt=2, defines=defines, log=GEN / f"{name}.cc.log")
        return (exe, None) if ok else (None, f"{self.cc.name} failed, see {name}.cc.log")

    def baselines(self, langs):
        out = {}
        if "c" in langs:
            exe = GEN / f"base_c{tc.EXE_SUFFIX}"
            ok, msg = self.cc.compile(BASEDIR / "spawn.c", exe, opt=2, log=GEN / "base_c.log")
            out["c"] = exe if ok else None
        if "cpp" in langs:
            exe = GEN / f"base_cpp{tc.EXE_SUFFIX}"
            ok, msg = self.cc.compile(BASEDIR / "spawn.cpp", exe, opt=2, cpp=True,
                                      log=GEN / "base_cpp.log")
            out["cpp"] = exe if ok else None
        if "rs" in langs:
            rustc = tc.find_rustc()
            exe = GEN / f"base_rs{tc.EXE_SUFFIX}"
            if rustc:
                code, o, e = tc.run_capture([rustc, "-O", "-C", "codegen-units=1", "-o", exe,
                                             BASEDIR / "spawn.rs"])
                tc.write_text(GEN / "base_rs.log", o + e)
                out["rs"] = exe if code == 0 else None
            else:
                out["rs"] = None
        return out


