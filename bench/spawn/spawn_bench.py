def select(benches, only):
    if not only:
        return benches
    keys = [k.strip() for k in only.split(",") if k.strip()]
    return [b for b in benches if any(b.id == k or b.family == k or
                                      (len(k) > 1 and b.id.startswith(k)) for k in keys)]


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--exe", help="the goose compiler (default: found as the tests find it)")
    ap.add_argument("--cc", help="C toolchain name (default: clang if present)")
